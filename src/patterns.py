from __future__ import annotations

import re


def rx(pattern: str, flags: int = 0) -> re.Pattern:
    return re.compile(pattern, flags)


def count(pattern: re.Pattern, text: str | None) -> int:
    if not text:
        return 0
    return len(pattern.findall(text))


def has(pattern: re.Pattern, text: str | None) -> bool:
    return bool(text) and pattern.search(text) is not None


def first_pos(pattern: re.Pattern, text: str | None) -> int | None:
    if not text:
        return None
    m = pattern.search(text)
    return m.start() if m else None


